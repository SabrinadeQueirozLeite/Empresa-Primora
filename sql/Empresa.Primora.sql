-- 1. A coluna guarda o bairro já tratado, então o nome passa a ser "bairro" (como no MER)
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'endereco' AND column_name = 'bairro_informado'
    ) THEN
        ALTER TABLE endereco RENAME COLUMN bairro_informado TO bairro;
    END IF;
END $$;

-- 2. Colunas pequenas demais para os textos da auditoria e da ViaCEP
ALTER TABLE auditoria
    ALTER COLUMN valor_original TYPE text,
    ALTER COLUMN valor_tratado  TYPE text,
    ALTER COLUMN criterio       TYPE text;

ALTER TABLE endereco
    ALTER COLUMN logradouro TYPE varchar(150),
    ALTER COLUMN complemento TYPE varchar(100),
    ALTER COLUMN bairro TYPE varchar(100),
    ALTER COLUMN cidade TYPE varchar(60);

-- 3. Relação 1:1 entre empresa e endereço (MER)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_endereco_empresa'
    ) THEN
        ALTER TABLE endereco ADD CONSTRAINT uq_endereco_empresa UNIQUE (id_empresa);
    END IF;
END $$;

-- 4. Colunas de id que precisam gerar o número sozinhas (erro "valor nulo na coluna id_telefone").
--    Só mexe nas que ainda não geram: se já forem serial ou identity, não faz nada.
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('vendedor',   'id_vendedor'),
            ('endereco',   'id_endereco'),
            ('telefone',   'id_telefone'),
            ('auditoria',  'id_auditoria')
        ) AS t(tabela, coluna)
    LOOP
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = r.tabela
              AND column_name = r.coluna
              AND column_default IS NULL
              AND is_identity = 'NO'
        ) THEN
            EXECUTE format(
                'ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
                r.tabela, r.coluna
            );
        END IF;
    END LOOP;
END $$;